import uuid
from datetime import datetime
from typing import Annotated, Any

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, computed_field

Email = Annotated[
    str,
    StringConstraints(strip_whitespace=True, to_lower=True, min_length=3, max_length=255, pattern=r"^[^@\s]+@[^@\s]+\.[^@\s]+$"),
]
Password = Annotated[str, StringConstraints(min_length=8, max_length=72)]
Title = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]


class Credentials(BaseModel):
    email: Email
    password: Password


class UserOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    email: str


class TokenOut(BaseModel):
    access_token: str
    token_type: str = "bearer"
    user: UserOut


class SectionCreate(BaseModel):
    title: Title | None = None


class SectionUpdate(BaseModel):
    title: Title


class SectionOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    title: str | None
    question_count: int
    max_questions: int
    status: str
    created_at: datetime
    updated_at: datetime

    @computed_field
    @property
    def remaining(self) -> int:
        return max(self.max_questions - self.question_count, 0)


class MessageCreate(BaseModel):
    content: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=4000)]
    # Generated by the client per submission so network retries don't consume another question slot.
    client_message_id: Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9_-]{8,100}$")] | None = None


class MessageOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    role: str
    content: str
    citations: list[dict[str, Any]] | None
    status: str
    reply_to_id: uuid.UUID | None
    created_at: datetime


class DocumentOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    filename: str
    content_type: str
    size_bytes: int
    status: str
    error: str | None
    chunk_count: int
    created_at: datetime
    # processing | done | failed, or None before figures are looked for.
    figure_status: str | None = None
    figure_count: int = 0
    # On upload only: "existing" when the same file was already in the student's library (that
    # document was attached instead), "already_in_chat" when it was already attached.
    duplicate: str | None = None


class AttachDocument(BaseModel):
    document_id: uuid.UUID


class QuizCreate(BaseModel):
    num_questions: int = Field(default=5, ge=1, le=15)
    topic: Annotated[str, StringConstraints(strip_whitespace=True, max_length=200)] | None = None


class QuizQuestionOut(BaseModel):
    question: str
    options: list[str]


class QuizOut(BaseModel):
    id: uuid.UUID
    section_id: uuid.UUID
    topic: str | None
    created_at: datetime
    questions: list[QuizQuestionOut]


class AttemptCreate(BaseModel):
    answers: list[int | None]


class QuestionResult(BaseModel):
    question: str
    options: list[str]
    selected: int | None
    correct_index: int
    is_correct: bool
    explanation: str
    citation: dict[str, Any] | None


class AttemptOut(BaseModel):
    id: uuid.UUID
    score: int
    total: int
    results: list[QuestionResult]
